"""Runtime shadows of formally specified operation contracts.

The Lean files own the mathematical distinction between exact operation
semantics and the weaker relation established by local validation.  These
immutable values make that same distinction inspectable at the Python
boundary.  They are plans and audit data, not proof objects.

Only saturation is instantiated here.  Copying every current constructor into
a speculative framework would turn enum prose into a second ontology before
the first contract has been exercised.
"""

from dataclasses import dataclass
from types import MappingProxyType

from . import kernel as K


@dataclass(frozen=True)
class ValidationObligation:
    """One independently checkable part of an operation's local guarantee."""

    name: str
    verifier_subject: str
    verifier_function: str
    establishes: str


@dataclass(frozen=True)
class OperationContract:
    """Backend-neutral semantic and validation boundary for an operation."""

    kind: str
    source_sort: str
    target_sort: str
    parameters: tuple
    preconditions: tuple
    semantic_relation: str
    edge_type: str
    built_endpoint: str
    source_endpoint: str
    transport_reason: str
    checked_obligations: tuple
    open_obligations: tuple
    licensed_consequences: tuple

    def __post_init__(self):
        if self.edge_type not in K.ALL_TYPES:
            raise ValueError("%s names unknown edge type %s"
                             % (self.kind, self.edge_type))
        if {self.built_endpoint, self.source_endpoint} != {"src", "dst"}:
            raise ValueError("%s must orient built and source endpoints"
                             % self.kind)
        names = [obligation.name for obligation in self.checked_obligations]
        if len(names) != len(set(names)):
            raise ValueError("%s repeats a checked obligation" % self.kind)
        if not self.semantic_relation or not self.checked_obligations:
            raise ValueError("%s is missing semantics or validation" % self.kind)

    @property
    def derivation(self):
        return self.edge_type, self.transport_reason


SATURATION = OperationContract(
    kind="SaturateClosure",
    source_sort="ideal in an exact polynomial ring",
    target_sort="ideal in the same exact polynomial ring",
    parameters=("polynomial f",),
    preconditions=(
        "source and built ideals are interpreted in the same ring",
        "f is an expression in that ring",
        "the built ideal is generated by exactly the recorded output generators",
    ),
    semantic_relation="I(built) = I(source) : f^oo",
    edge_type=K.NECESSARY_CONDITION,
    built_endpoint="src",
    source_endpoint="dst",
    transport_reason=(
        "I : f^oo contains I, so the saturated model is cut by more "
        "equations; returning to the ambient model drops them"
    ),
    checked_obligations=(
        ValidationObligation(
            "source_containment",
            "edge",
            "containment",
            "I(source) is contained in I(built)",
        ),
        ValidationObligation(
            "no_invented_generators",
            "operation",
            "operation_output",
            "every recorded generator of I(built) has a certified witness "
            "in I(source) : f^oo",
        ),
    ),
    open_obligations=(
        "I(source) : f^oo is contained in I(built) (output completeness)",
    ),
    licensed_consequences=(
        "the entire built ideal is contained in I(source) : f^oo "
        "(generator certificates lift through ideal generation)",
        "source ideal identities hold on the built model "
        "(NECESSARY_CONDITION/AGAINST)",
    ),
)


ELIMINATION = OperationContract(
    kind="Eliminate",
    source_sort="ideal in source exact polynomial ring R",
    target_sort="ideal in retained-coordinate exact polynomial ring S",
    parameters=(
        "coordinate inclusion S -> R",
        "eliminated/retained variable partition",
    ),
    preconditions=(
        "retained and eliminated variables are disjoint and partition the source ring",
        "source and built rings have the same exact coefficient domain",
        "the built ideal is generated by exactly the recorded output generators",
    ),
    semantic_relation="I(built) = inclusion^-1(I(source))",
    edge_type=K.IMAGE_CLOSURE,
    built_endpoint="dst",
    source_endpoint="src",
    transport_reason=(
        "exact elimination contracts the source ideal to the retained-coordinate "
        "ring; geometrically it presents the scheme-theoretic image, while "
        "point-set closure needs additional field/radical hypotheses"
    ),
    checked_obligations=(
        ValidationObligation(
            "generator_expressibility",
            "operation",
            "operation_output",
            "every recorded output generator is an expression in the retained ring",
        ),
        ValidationObligation(
            "generator_source_membership",
            "operation",
            "operation_output",
            "every recorded output generator maps into the source ideal",
        ),
        ValidationObligation(
            "section_completeness",
            "elimination",
            "elimination_section",
            "a polynomial retraction fixes the retained ring and carries the "
            "entire source ideal into the recorded target ideal",
        ),
    ),
    open_obligations=(
        "general completeness certificates for exact eliminations with no polynomial section",
        "point-set closure identification needs explicit field and radical hypotheses",
    ),
    licensed_consequences=(
        "the entire built ideal is contained in the contraction of the source ideal",
        "target identities pull back to source identities (IMAGE_CLOSURE/AGAINST)",
        "source points map to target points, so target emptiness implies source emptiness",
        "a verified section plus no-invention licenses source-derived retained-ring identities along",
    ),
)


CONTRACTS = MappingProxyType({
    SATURATION.kind: SATURATION,
    ELIMINATION.kind: ELIMINATION,
})


def for_operation(kind):
    """Return the formalization-backed runtime contract, if one exists."""

    return CONTRACTS.get(kind)
